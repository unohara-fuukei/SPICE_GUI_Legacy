// WebView 75 compatibility: flexbox `gap` landed in Chromium 84, so every
// inline `style="... display: flex; ... gap: Npx; ..."` collapses its spacing
// on Chromium 75 (the WebView pinned by some Android 10 devices).
//
// This script scans src/**/*.svelte for inline flex+gap styles and generates
// `src/lib/webview75-inline-gap.css`, a static stylesheet that re-creates the
// spacing via attribute-substring selectors (`[style*="gap: 4px"] > * + *`).
// It runs as part of `prebuild` so template changes stay in sync.
//
// Fallback semantics (documented limitations):
//  - `> * + *` margins reproduce gap for single-line flex rows/columns.
//  - Wrapped rows (flex-wrap: wrap) get the correct inline spacing but keep a
//    leading margin at the start of wrapped lines (7 call sites at the time of
//    writing) — accepted cosmetic drift.
//  - A child that sets its own margin-left/margin-top can override the
//    fallback in the same axis; gap semantics would have added both.
import fs from 'fs';
import path from 'path';

const ROOT = path.resolve(process.cwd());
const OUT = path.join(ROOT, 'src/lib/webview75-inline-gap.css');

function* walkSvelte(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === '.svelte-kit' || entry.name === 'build') continue;
      yield* walkSvelte(p);
    } else if (entry.name.endsWith('.svelte')) {
      yield p;
    }
  }
}

const files = [];
try {
  // fs.glob (Node 22+)
  for (const f of fs.globSync(path.join(ROOT, 'src/**/*.svelte'))) files.push(f);
} catch {
  for (const f of walkSvelte(path.join(ROOT, 'src'))) files.push(f);
}

const seen = new Set(); // `${gapTok}|${displayTok}|${direction}` tokens, exact spellings
let count = 0;

for (const file of files) {
  const src = fs.readFileSync(file, 'utf8');
  for (const m of src.matchAll(/style="([^"]*)"/g)) {
    const style = m[1];
    if (!/gap\s*:/.test(style)) continue;
    // must be flex (grid gap is native in Chromium 75)
    if (!/display\s*:\s*(inline-)?flex/.test(style)) continue;
    const gap = style.match(/(?:^|;)\s*gap\s*:\s*([^;"]+)/);
    if (!gap) continue;
    let gapVal = gap[1].trim();
    if (/var\(|calc\(|%/.test(gapVal)) continue; // non-static gap: cannot build a margin fallback
    // two-value gap: `A B` (row-gap column-gap) — keep both axes
    const displayTok = style.match(/display\s*:\s*((?:inline-)?flex)/)[1];
    let dir = 'row';
    const dm = style.match(/flex-direction\s*:\s*([\w-]+)/);
    if (dm) dir = dm[1];
    const wrap = /flex-wrap\s*:\s*wrap/.test(style);
    seen.add(JSON.stringify([gapVal, displayTok, dir, wrap]));
    count++;
  }
}

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

const lines = [];
lines.push('/* ============================================================');
lines.push(' * GENERATED by scripts/webview75-gen-inline-gap-css.mjs — do not');
lines.push(' * edit by hand; rerun `pnpm prebuild` to regenerate.');
lines.push(' * Flexbox gap fallback for Chromium 75 WebView (gap: flex since 84):');
lines.push(' * re-creates inline `style="...display: flex...gap: Npx..."` spacing');
lines.push(' * via attribute-substring selectors + `> * + *` margins.');
lines.push(' * Grid gap is native since Chromium 57 and is intentionally untouched.');
lines.push(' * ============================================================ */');
lines.push('');

// De-duplicate: for direction detection we do NOT need displayTok, but keeping
// the display requirement reduces false positives on elements whose style
// mentions flex-direction but a different display (rare). We emit selectors
// keyed on (gap, direction) and require a flex display token as a guard.
const byDir = new Map(); // dir -> Set(gapVal)
for (const raw of seen) {
  const [gapVal, , dir, wrap] = JSON.parse(raw);
  const key = dir + (wrap ? '|wrap' : '');
  if (!byDir.has(key)) byDir.set(key, new Set());
  byDir.get(key).add(gapVal);
}

// Order matters only between rules that can match the same element; the
// :not() guards below make row / column / reverse selectors mutually exclusive.
const marginFor = {
  row: 'margin-left',
  'row-reverse': 'margin-right',
  column: 'margin-top',
  'column-reverse': 'margin-bottom',
};
// axis reset so a column container does not also receive the row fallback
const resetFor = {
  'row-reverse': 'margin-left: 0;',
  'column-reverse': 'margin-top: 0;',
};

for (const [key, gaps] of byDir) {
  const [dir, wrap] = key.split('|');
  const mg = marginFor[dir] ?? 'margin-left';
  const reset = resetFor[dir] ?? '';
  for (const g of [...gaps].sort()) {
    let guard;
    if (dir === 'row') {
      // matches both "direction absent" and "explicit row"; excludes every
      // other direction spelling ("row" is a substring of "row-reverse"!)
      guard = [
        'flex-direction:column', 'flex-direction: column',
        'flex-direction:column-reverse', 'flex-direction: column-reverse',
        'flex-direction:row-reverse', 'flex-direction: row-reverse',
      ].map((s) => `:not([style*="${s}"])`).join('');
    } else {
      const d = dir.startsWith('row') ? 'row' : 'column';
      guard = `:not([style*="flex-direction:${d}-reverse"]):not([style*="flex-direction: ${d}-reverse"])`;
    }
    // Build: [display flex-ish][direction guard][gap] > * + *
    const sels = [];
    for (const dd of ['display: flex', 'display:flex', 'display: inline-flex', 'display:inline-flex']) {
      for (const gg of [`gap: ${g}`, `gap:${g}`]) {
        sels.push(`[style*="${esc(dd)}"]${guard}[style*="${esc(gg)}"] > * + *`);
      }
    }
    lines.push(`/* ${dir}${wrap ? ' +wrap' : ''} gap: ${g} */`);
    lines.push(`${sels.join(',\n')} {`);
    lines.push(`  ${mg}: ${g};`);
    if (reset) lines.push(`  ${reset}`);
    lines.push('}');
    lines.push('');
  }
}

fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(
  `✅ [webview75] inline flex+gap fallback generated: ${count} inline styles → ${byDir.size} direction groups → ${OUT}`
);
